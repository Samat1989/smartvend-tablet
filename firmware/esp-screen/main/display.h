// LVGL поверх собственного QSPI-слоя панели.
#pragma once

#include <stdbool.h>

#include "esp_err.h"
#include "lvgl.h"

// Поднимает панель, LVGL и тач, запускает задачу отрисовки.
esp_err_t display_start(void);

// Показать экран и снести предыдущий.
//
// lv_screen_load сам старый экран не удаляет, и каждый переход оставлял его в
// памяти: через десяток нажатий плата падала. Удаление отложенное — сносить
// экран прямо из обработчика его же кнопки нельзя.
void display_load_screen(lv_obj_t *scr);

// Блокировка LVGL: библиотека не потокобезопасна, а рисуем мы из своей задачи,
// пока экраны покупки живут в другой. Брать перед любым обращением к lv_*.
bool display_lock(uint32_t timeout_ms);
void display_unlock(void);
