// Тонкий слой QSPI для панели AXS15231B на JC3248W535.
//
// Написан вместо esp_lcd_panel_io_spi по одной причине: этой панели команды
// нужно слать командой и адресом по четырём линиям
// (SPI_TRANS_MULTILINE_CMD | SPI_TRANS_MULTILINE_ADDR), а esp_lcd всегда шлёт
// команду по одной. Панель молча не принимает инициализацию — ни ошибки, ни
// картинки. Проверено на плате: эталонный скетч на Arduino_GFX, который шлёт
// команды по четырём линиям, экран зажигает; та же конфигурация через esp_lcd —
// нет.
#pragma once

#include <stddef.h>
#include <stdint.h>

#include "esp_err.h"

// Поднимает шину, панель и подсветку. После успеха можно рисовать.
esp_err_t panel_qspi_init(void);

// Отправляет кадр целиком: 320×480 в RGB565, старший байт вперёд.
// Блокирующая — возвращается, когда данные ушли на панель.
esp_err_t panel_qspi_draw_frame(const void *pixels);
